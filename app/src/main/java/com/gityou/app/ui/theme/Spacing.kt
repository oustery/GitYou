package com.gityou.app.ui.theme

import androidx.compose.ui.unit.dp

/*
 * Spacing scale in multiples of 4 dp. Compose screens from these tokens
 * instead of arbitrary paddings: hero sections get generous air, dense
 * utility lists stay tighter.
 */
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
    val hero = 48.dp
}
